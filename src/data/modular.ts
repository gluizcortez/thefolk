/** Os móveis antigos com kit (a aparência agora sai das peças). */
export function withKit(def: ObjectDef): ObjectDef {
  const kit = KITS[def.id];
  return kit ? { ...def, kit } : def;
}

const decor = (amb: number): InteractionDef[] => (amb >= 3 ? [{ id: 'admire', label: 'act.admire', duration: 10, effects: { fun: 0.3 }, until: 'fun' }] : []);

/** Enfeite de pôr em cima de mesa, bancada, criado-mudo. */
const ornament = (id: string, price: number, ambience: number, extra: Partial<ObjectDef> = {}): ObjectDef => ({
  id,
  name: `obj.${id}`,
  price,
  category: 'decor',
  art: id,
  size: { w: 1, h: 1 },
  ambience,
  layer: 'surface',
  turns8: true,
  interactions: decor(ambience),
  ...extra,
});

