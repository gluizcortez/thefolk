// Bloco 4: catálogo em faixas de preço. Cada função de necessidade ganha uma
// versão barata (tier 0) e uma cara (tier 2) ao lado do modelo médio que já
// existia (em objects.ts). A diferença não é só de preço: a cara enche mais
// rápido, dá conforto junto, melhora o cômodo e gasta menos; a barata quebra
// mais e enfeia. Também chegam os objetos de diversão com atividade a dois,
// a mesa e as cadeiras separadas e mais coisas de pendurar na parede.

