/** Mapa w x h todo de `fill`, com retângulos pintados por cima ([x0, y0, x1, y1] inclusive). */
function sketch(w: number, h: number, fill: string, paint: [number, number, number, number, string][]): string[] {
  const rows = Array.from({ length: h }, () => Array.from({ length: w }, () => fill));
  for (const [x0, y0, x1, y1, ch] of paint) {
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) rows[y][x] = ch;
  }
  return rows.map((r) => r.join(''));
}

